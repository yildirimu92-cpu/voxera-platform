async function applyVoxeraBrand(buffer) {
  const pdf = await PDFDocument.load(buffer);
  const page = pdf.getPages()[0];
  if (!page) return buffer;

  const logo = await pdf.embedPng(Buffer.from(VOXERA_LOGO_PNG_BASE64, 'base64'));
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const navy = rgb(13 / 255, 31 / 255, 60 / 255);

  // Replace the plain text wordmark generated by the base template with the
  // official icon plus a clean Voxera wordmark. The creditor line below stays
  // untouched.
  page.drawRectangle({ x: 34, y: 781, width: 170, height: 40, color: rgb(1, 1, 1) });
  page.drawImage(logo, { x: 42, y: 784, width: 28, height: 28 });
  page.drawText('VOXERA', { x: 79, y: 790, size: 18, font: bold, color: navy });

  return Buffer.from(await pdf.save());
}

async function generateSwissQrInvoicePdf(args) {
  const generated = await generateBasePdf(args);
  return {
    ...generated,
    buffer: await applyVoxeraBrand(generated.buffer)
  };
}

